// Writes <root>/.agenticeditor/gen/: a static import map of the film's sections, shared by the editor (Vite) and the
// renderer (Remotion's webpack). Regenerated whenever film.json changes, so adding a section is a manifest edit.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readManifest, type Paths } from "./state";

export const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export function generate(p: Paths) {
  const m = readManifest(p);
  fs.mkdirSync(p.gen, { recursive: true });
  const rel = (f: string) => {
    const r = path.relative(p.gen, f).split(path.sep).join("/");
    return r.startsWith(".") ? r : `./${r}`;
  };
  const components = [...new Set(m.sections.map((s) => s.component ?? s.id))];
  const present = components.filter((c) => ["tsx", "jsx", "ts"].some((ext) => fs.existsSync(path.join(p.sections, `${c}.${ext}`))));
  const lines = [
    "// generated by agenticeditor from film/film.json; do not edit",
    `import manifestJson from "${rel(p.manifest)}";`,
    ...present.map((c, i) => `import S${i} from "${rel(path.join(p.sections, c))}";`),
    `import type { Manifest } from "${rel(path.join(PKG, "src/core/manifest"))}";`,
    `export const manifest = manifestJson as unknown as Manifest;`,
    `export const sections = { ${present.map((c, i) => `${JSON.stringify(c)}: S${i}`).join(", ")} } as Record<string, any>;`,
    "",
  ];
  writeIfChanged(path.join(p.gen, "film.gen.ts"), lines.join("\n"));
  writeIfChanged(
    path.join(p.gen, "remotion-entry.tsx"),
    [
      "// generated by agenticeditor; the Remotion entry for stills and renders",
      `import { registerRoot, staticFile } from "remotion";`,
      `import { makeRoot } from "${rel(path.join(PKG, "src/film/Film"))}";`,
      `import { manifest, sections } from "./film.gen";`,
      `registerRoot(makeRoot({ manifest, sections, audioSrc: manifest.audio ? staticFile(manifest.audio) : undefined }));`,
      "",
    ].join("\n"),
  );
  return { missing: components.filter((c) => !present.includes(c)) };
}

function writeIfChanged(file: string, text: string) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return;
  fs.writeFileSync(file, text);
}
